#!/usr/bin/env python3
"""Verify the distributable net and generate its C++ byte array offline."""
import hashlib
from pathlib import Path

src = Path(__file__).resolve().parent.parent / "src"
name = "jieqi-b395f77e3ee9.nnue.zst"
expected = "b395f77e3ee9520900512ee6697d8ae2c384c040491cafb33b893d3715e0b71e"
data = (src / name).read_bytes()
if hashlib.sha256(data).hexdigest() != expected:
    raise SystemExit(f"SHA-256 mismatch: {name}")
out = src / "nnue/embedded_net.h"
header = "// Generated by scripts/embed-net.py; do not edit.\n"
header += "alignas(64) static const unsigned char EmbeddedNet[] = {\n"
header += "".join(
    ",".join(f"0x{b:02x}" for b in data[i:i + 32]) + ",\n"
    for i in range(0, len(data), 32)
)
header += "};\n"
if not out.exists() or out.read_text() != header:
    out.write_text(header)
print(f"Verified and embedded {name} ({len(data)} bytes)")
